def alive(pid):
    result = subprocess.run(["/bin/ps", "-o", "stat=", "-p", str(pid)],
                            capture_output=True, text=True, timeout=2)
    return bool(result.stdout.strip()) and not result.stdout.lstrip().startswith("Z")


class ExportHome(fixture.ReportHome):
    def setUp(self):
        super().setUp()
        self.rtk.write_text("#!%s\n%s" % (sys.executable, EXPORT_FAKE))
        self.rtk.chmod(0o700)
        clock = mock.patch.object(self.mod, "now_epoch", return_value=EPOCH)
        self.clock = clock.start()
        self.addCleanup(clock.stop)
        previous_umask = os.umask(0o077)
        self.addCleanup(os.umask, previous_umask)
        self.export_dir = self.home / ".copilot/copilot-s-rtk-export"
        self.version_dir = self.export_dir / "v1"
        self.publications = self.version_dir / "runs"

    def target(self, rec):
        return self.publications / (rec["run_id"] + ".json")

    def published(self, rec):
        return json.loads(self.target(rec).read_bytes())

    def calls(self, rec):
        path = self.path(rec["run_id"]) / "raw/rtk/fake-calls.jsonl"
        return [json.loads(s) for s in path.read_text().splitlines()] if path.exists() else []

    def invoke(self, *args):
        stdout, stderr = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            code = self.mod.main([str(a) for a in args])
        self.assertEqual(code, 0, stdout.getvalue() + stderr.getvalue())

    def start_real_run(self, index=0, *, resume=None, otel=False, mode="rtk"):
        rid = IDS[index]
        args = ["start", "--run-id", rid, "--mode", mode, "--cwd", self.cwd,
                "--launch-kind", "resume" if resume else "new",
                "--usage-file-owner", "caller", "--plugin-dir", fixture.PLUGIN,
                "--copilot-s-version", "0.0.0-test"]
        if resume:
            args += ["--resume-session-id", resume]
        if otel:
            args += ["--otel-file", self.home / (
                ".copilot/otel/copilot-otel-20261110-120000-%s.jsonl" % rid)]
        self.invoke(*args)
        return self.record(rid)

    def write_real_evidence(self, rec, *, conversations=None, hook=None):
        # Only synthetic child output: do not author stored finalized proof.
        if conversations is not None:
            fixture.write(rec["otel"]["file"],
                          "".join(json.dumps(fixture.span(sid=s)) + "\n" for s in conversations))
            for sid in conversations:
                (self.states / sid).mkdir(mode=0o700, exist_ok=True)
        if hook is not None:
            fixture.write(self.path(rec["run_id"]) / "hook-events.jsonl",
                          "".join(json.dumps({"decision": "rewritten", "sid": s}) + "\n" for s in hook))

    def finish_real_run(self, rec, *, launcher_sid=None):
        args = ["finish", "--run-id", rec["run_id"], "--exit-code", 0,
                "--launched-epoch", EPOCH, "--ended-epoch", EPOCH,
                "--session-state-dir", self.states]
        if launcher_sid:
            args += ["--session-id", launcher_sid]
        self.invoke(*args)
        final = self.record(rec["run_id"])
        self.assertEqual(final["state"], "completed")
        return final

    def finalized_real_run(self, index=0, *, resume=None, conversations=(SID,),
                           hook=(SID,), launcher_sid=None, gain=None):
        rec = self.start_real_run(index, resume=resume, otel=conversations is not None)
        self.write_real_evidence(rec, conversations=conversations, hook=hook)
        if gain is not None:
            self.gain(rec["run_id"], gain)
        return self.finish_real_run(rec, launcher_sid=launcher_sid)

    def cycle(self, rec, evidence=None):
        return self.mod._publisher_cycle(rec["run_id"], str(self.path(rec["run_id"])),
                                         evidence, None, lambda: False)

    def link(self, rec):
        if self.mod._is_finalized(rec):
            return self.mod.finalized_publication_run(rec)["session"]
        return self.mod._PublisherEvidence(rec).session_link(rec)

    def golden(self):
        negative = copy.deepcopy(fixture.GAIN)
        negative["summary"].update(total_saved=-200, total_output=1200, avg_savings_pct=None)
        final = self.finalized_real_run(gain=negative)
        self.assertEqual(final["otel"]["file"], "present")
        self.assertEqual(final["session"]["basis"], "single-conversation-id-in-own-otel-file")
        self.assertEqual(self.published(final)["run"]["session"], {
            "link": "confirmed", "id": SID, "proof": "single-conversation-id-in-own-otel-file",
            "corroborated_by": ["rtk-hook"]})
        return self.target(final).read_bytes()

    def wait_for(self, condition, *, timeout=5):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if condition():
                return
            time.sleep(.025)
        self.assertTrue(condition(), "bounded wait expired")

    def stop_worker(self, proc):
        if proc.poll() is None:
            proc.terminate()
            try:
                proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                with contextlib.suppress(ProcessLookupError):
                    os.killpg(proc.pid, signal.SIGKILL)
                proc.kill()
                proc.wait(timeout=3)

    def worker(self, rec):
        proc = subprocess.Popen([sys.executable, str(fixture.HELPER), "rtk-publisher",
                                 "--run-id", rec["run_id"], "--parent-pid", str(os.getpid())],
                                env=self.env, cwd=self.cwd, stdin=subprocess.DEVNULL,
                                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        self.addCleanup(self.stop_worker, proc)
        return proc


