    def clone_publication(self, template, index):
        payload = copy.deepcopy(template)
        payload["run"]["run_id"] = IDS[index]
        return payload

    def put_publication(self, payload):
        rid = payload["run"]["run_id"]
        path = self.publications / (rid + ".json")
        path.write_bytes(self.mod.encode_publication(payload, rid))
        path.chmod(0o600)
        return path

    def fill_capacity(self, template, count=256):
        for index in range(count):
            payload = self.clone_publication(template, index)
            if payload["run"]["record_state"] == "finalized":
                stamp = self.mod.iso(EPOCH - 3600 + index)
                payload["run"]["finalized_at"] = stamp
                payload["run"]["rtk"]["measured_at"] = stamp
                payload["published_at"] = self.mod.iso(EPOCH - 3000 + index)
            self.put_publication(payload)

    def pool_snapshot(self):
        result = {}
        for path in self.publications.glob("*.json"):
            info = path.lstat()
            body = None
            if stat.S_ISLNK(info.st_mode):
                body = os.readlink(path)
            elif stat.S_ISREG(info.st_mode) and info.st_mode & stat.S_IRUSR:
                body = path.read_bytes()
            result[path.name] = (info.st_dev, info.st_ino, info.st_mode, info.st_uid,
                                 info.st_nlink, info.st_size, info.st_mtime_ns, body)
        return result

    def canonical_snapshot(self):
        return {str(p.relative_to(self.home)): (p.read_bytes(), p.stat().st_mtime_ns)
                for p in (self.home / ".copilot/session-reports").rglob("run.json")}

    def assert_pool_delta(self, before, *, removed=(), added=()):
        after = self.pool_snapshot()
        self.assertEqual(set(after), (set(before) - set(removed)) | set(added))
        for name in set(before) - set(removed):
            self.assertEqual(after[name], before[name], name)
        self.assertEqual(len(after), 256)
        return after

