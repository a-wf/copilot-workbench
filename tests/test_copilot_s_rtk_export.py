        for _ in range(2):
            self.assertEqual(self.cycle(rec, evidence)[0], "published")
        out = self.published(rec)["run"]
        self.assertEqual(out["rtk"]["stats"]["total_commands"], 2, "cumulative, never summed")
        self.assertEqual(out["session"]["id"], SID)
        self.assertEqual(len(self.calls(rec)), 3)
        for call in self.calls(rec):
            self.assertEqual(call["argv"], ["gain", "--format", "json"])
            self.assertEqual(call["cwd"], str(self.path(rec["run_id"]) / "raw/rtk"))
            self.assertEqual(call["env"], self.mod.rtk_env_for(str(self.path(rec["run_id"]))))
        after = self.snapshot()
        for key, value in before.items():
            self.assertEqual(after[key], value, key)

