        self.assertEqual(self.mod.load_run_for_export(rec["run_id"])["run_id"], rec["run_id"])
        with record.open("ab") as out:
            out.write(b" ")
        with self.assertRaises(self.mod.ReportError):
            self.mod.load_run_for_export(rec["run_id"])

