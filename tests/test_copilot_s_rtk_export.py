    def test_timeout_flood_and_cancel_kill_owned_child_group(self):
        for failure in ("timeout", "flood", "cancel"):
            with self.subTest(failure=failure):
                pidfile = self.home / ("child-" + failure)
                code = (
                    "import os,pathlib,subprocess,sys,time\n"
                    "child=subprocess.Popen([sys.executable,'-c','import time; time.sleep(20)'])\n"
                    "pathlib.Path(sys.argv[1]).write_text(str(child.pid))\n"
                    + ("os.write(1,b'x'*1000000)\n" if failure == "flood" else "")
                    + "time.sleep(20)\n")
                start = time.monotonic()
                rfd, wfd = os.pipe()
                try:
                    stop = lambda: failure == "cancel" and pidfile.exists()
                    if failure == "cancel":
                        # Exercise the cancellation predicate while the child owns
                        # the pipe; cancel_fd is independently covered below.
                        expected = "cancelled"
                    else:
                        expected = "output too large" if failure == "flood" else "timed out"
                    with self.assertRaisesRegex(self.mod.ReportError, expected):
                        self.mod.bounded_capture([sys.executable, "-c", code, str(pidfile)],
                                                 self.env, str(self.home), .6 if failure != "cancel" else 3,
                                                 4096, cancel_fd=rfd, should_stop=stop)
                    self.assertLess(time.monotonic() - start, 4)
                    pid = int(pidfile.read_text())
                    self.wait_for(lambda: not alive(pid), timeout=2)
                finally:
                    os.close(rfd)
                    os.close(wfd)
                    if pidfile.exists() and alive(int(pidfile.read_text())):
                        with contextlib.suppress(ProcessLookupError):
                            os.kill(int(pidfile.read_text()), signal.SIGKILL)

