    def test_run_lock_and_atomic_failure_preserve_previous_and_remove_temp_files(self):
        rec = self.start_real_run(resume=SID)
        self.gain(rec["run_id"])
        self.cycle(rec)
        before = self.target(rec).read_bytes()
